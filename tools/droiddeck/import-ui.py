#!/usr/bin/env python3
"""Emit an apply_patch patch importing the pinned Android presentation catalogue."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=Path)
args = parser.parse_args()
root = args.source
pin = "0a07926ef3477c90db911d169904137cfc5e2505"
assert subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip() == pin

def strings(folder):
    result = {}
    for path in sorted((root / "app/src/main/res" / folder).glob("*.xml")):
        for item in ET.parse(path).getroot():
            if item.tag == "string":
                result[item.attrib["name"]] = "".join(item.itertext()).replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"')
    return result

en = strings("values")
zh = dict(en, **strings("values-zh-rCN"))
ui = root / "app/src/main/java/com/droiddeck/launcher/ui"

def call_end(source, start):
    depth, quoted, escape = 1, False, False
    for i in range(start, len(source)):
        c = source[i]
        if quoted:
            if escape:
                escape = False
            elif c == "\\":
                escape = True
            elif c == '"':
                quoted = False
        elif c == '"':
            quoted = True
        elif c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                return i
    return start

panels, manifest = {}, []
for path in sorted(ui.glob("*.kt")):
    source = path.read_text()
    rows, seen = [], set()
    for match in re.finditer(r'\b(\w*(?:ToggleRow|SliderRow|ChoiceRow|SettingsGroup|SectionTitle|SettingRow|SelectRow|TextEntryRow|PrimaryButton|SecondaryButton))\s*\(', source):
        kind = match[1]
        chunk = source[match.end():call_end(source, match.end())]
        keys = re.findall(r'R\.string\.(\w+)', chunk)
        if not keys or keys[0] not in en or keys[0] in seen:
            continue
        seen.add(keys[0])
        role = "toggle" if "Toggle" in kind else "range" if "Slider" in kind else "heading" if kind in ("SettingsGroup", "SectionTitle") else "action" if "Button" in kind else "choice"
        rows.append({"kind": role, "key": keys[0], "detail": keys[1] if len(keys) > 1 and keys[1] in en else None,
                     "line": source[:match.start()].count("\n") + 1})
    panels[path.stem] = rows
    manifest.append({"file": str(path.relative_to(root)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                     "composables": re.findall(r'(?:internal |private )?fun (?:\w+\.)?(\w+)\(', source),
                     "strings": list(dict.fromkeys(re.findall(r'R\.string\.(\w+)', source))), "rows": len(rows)})

word = (ui / "Wordmark.kt").read_text()
letters = "".join(re.findall(r'"([^"]*)"', word.split("private const val LETTERS =", 1)[1]))
catalogue = {"version": "0.6.9", "commit": pin, "strings": {"en": en, "zh": zh}, "panels": panels,
             "wordmark": {"letters": letters, "left": re.search(r'LEFT_HALF = "([^"]+)"', word)[1],
                          "right": re.search(r'RIGHT_HALF = "([^"]+)"', word)[1]}}
outputs = {
    "app/Madeira/DroidDeckUI/catalog.js": "/* DroidDeck 0.6.9 presentation data; GPL-3.0. Generated by tools/droiddeck/import-ui.py. */\nwindow.DD_CATALOG = " + json.dumps(catalogue, ensure_ascii=False, separators=(",", ":")) + ";\n",
    "docs/droiddeck-source-manifest.json": json.dumps({"version":"0.6.9", "commit":pin, "files":manifest}, ensure_ascii=False, indent=2) + "\n",
    "app/Madeira/DroidDeckUI/LICENSE-DroidDeck.txt": (root / "LICENSE").read_text(),
}
print("*** Begin Patch")
for name, content in outputs.items():
    print("*** Add File: " + name)
    for line in content.splitlines():
        print("+" + line)
print("*** End Patch")
